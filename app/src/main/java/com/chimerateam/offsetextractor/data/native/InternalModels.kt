package com.chimerateam.offsetextractor.data.native

import com.google.gson.annotations.SerializedName

/**
 * Counts of the internal C++ extraction.
 *
 * The full table can be hundreds of thousands of rows, so only these counts and
 * the path of the streamed NDJSON file cross the JNI boundary.
 *
 * @property classes number of RTTI classes.
 * @property vtableSlots number of virtual slots across every class.
 * @property functions number of functions in the table.
 * @property named functions with a derived name.
 * @property autoNamed functions named `sub_<hex>`.
 * @property verified functions confirmed by a second source.
 * @property ambiguous signatures or anchors with more than one candidate.
 * @property notFound signatures or anchors with no candidate.
 * @property signatures auto-generated signatures.
 * @property signaturesUnique signatures that matched exactly one function start.
 * @property slotsWithSizeZero virtual slots whose function has no size.
 * @property dataSymbols data symbols moved out of the function table.
 * @property truncatedSignatures whether the signature cap truncated generation.
 * @property path absolute path of the NDJSON table in the app cache.
 */
data class InternalSummary(
    val classes: Int = 0,
    @SerializedName("vtableSlots") val vtableSlots: Int = 0,
    val functions: Int = 0,
    val named: Int = 0,
    @SerializedName("autoNamed") val autoNamed: Int = 0,
    val verified: Int = 0,
    val ambiguous: Int = 0,
    @SerializedName("notFound") val notFound: Int = 0,
    val signatures: Int = 0,
    @SerializedName("signaturesUnique") val signaturesUnique: Int = 0,
    @SerializedName("slotsWithSizeZero") val slotsWithSizeZero: Int = 0,
    @SerializedName("dataSymbols") val dataSymbols: Int = 0,
    @SerializedName("truncatedSignatures") val truncatedSignatures: Boolean = false,
    val path: String = "",
    @SerializedName("tableBytes") val tableBytes: Long = 0,
    val rows: Int = 0,
    val shards: List<ShardPart> = emptyList(),
    @SerializedName("classMapPath") val classMapPath: String = "",
    @SerializedName("categoriesApplied") val categoriesApplied: Boolean = false,
    @SerializedName("truncatedSlots") val truncatedSlots: Boolean = false,
    @SerializedName("truncatedSlotClasses") val truncatedSlotClasses: Int = 0
) {
    /** Whether the table holds anything worth showing. */
    val isEmpty: Boolean get() = functions == 0 && classes == 0

    /** Records across every category file. */
    val shardRows: Int get() = shards.sumOf { it.entries }
}

/**
 * One category document the engine wrote.
 *
 * The engine classifies as it streams, so these files are finished JSON
 * documents: the export copies them into the archive byte for byte.
 *
 * @property id file identifier, for example `block_placement` or
 *   `unnamed_part_02`.
 * @property category logical category.
 * @property label human-readable label.
 * @property part one-based part number.
 * @property classes classes in the file.
 * @property functions functions in the file.
 * @property symbols data symbols in the file.
 * @property path absolute path of the document.
 */
data class ShardPart(
    val id: String = "",
    val category: String = "",
    val label: String = "",
    val part: Int = 1,
    val classes: Int = 0,
    val functions: Int = 0,
    val symbols: Int = 0,
    val path: String = ""
) {
    /** Records in the file. */
    val entries: Int get() = classes + functions + symbols
}

/**
 * One function in the internal table.
 *
 * Addresses are kept as the `0x`-prefixed strings the engine writes, so the
 * model round-trips the NDJSON without a numeric conversion.
 *
 * @property address image-relative virtual address.
 * @property fileOffset offset inside the library file.
 * @property size size in bytes.
 * @property name best available name.
 * @property nameSource where the name came from.
 * @property aliases other names for the same address.
 * @property kind `function`, `thunk` or `pure_virtual`.
 * @property status verification status.
 * @property prologueKind recognised prologue form, `leaf` or `none`.
 * @property mangled mangled name when the best name is demangled.
 * @property target tail-call target for a thunk.
 * @property signature auto-generated byte signature.
 * @property signatureUnique whether the signature matched exactly once.
 */
data class InternalFunction(
    val address: String = "0x0",
    @SerializedName("fileOffset") val fileOffset: String = "0x0",
    val size: Long = 0,
    val name: String = "",
    @SerializedName("nameSource") val nameSource: String = "auto",
    val aliases: List<String> = emptyList(),
    val kind: String = "function",
    val status: String = "fde_only",
    @SerializedName("prologueKind") val prologueKind: String = "none",
    val mangled: String? = null,
    val target: String? = null,
    val signature: String? = null,
    @SerializedName("signatureUnique") val signatureUnique: Boolean? = null,
    @SerializedName("suspectReason") val suspectReason: String? = null
) {
    /** [address] as a number, or zero when it is not hex. */
    fun addressValue(): Long = parseHex(address)
}

/**
 * One virtual slot.
 *
 * @property slot slot index.
 * @property offset byte offset from the first function pointer.
 * @property address function virtual address.
 * @property fileOffset function file offset.
 * @property size function size when known.
 * @property name slot name.
 * @property kind `virtual`, `pure_virtual` or `thunk`.
 * @property overrides whether the slot differs from the first base.
 * @property inherited whether the slot is identical to the first base.
 * @property status verification status.
 * @property signature auto-generated signature.
 * @property signatureUnique whether it matched exactly once.
 */
data class VtableSlot(
    val slot: Int = 0,
    val offset: String = "0x0",
    val address: String = "0x0",
    @SerializedName("fileOffset") val fileOffset: String = "0x0",
    val size: Long = 0,
    val name: String = "",
    val kind: String = "virtual",
    @SerializedName("prologueKind") val prologueKind: String = "none",
    val overrides: Boolean = false,
    val inherited: Boolean = false,
    val status: String = "verified",
    val signature: String? = null,
    @SerializedName("signatureUnique") val signatureUnique: Boolean? = null
)

/**
 * One RTTI class and its slots.
 *
 * @property name demangled class name.
 * @property mangled mangled name.
 * @property bases base classes.
 * @property vtable vtable header address.
 * @property vtableOffset vtable offset from the image base.
 * @property typeInfo `type_info` address.
 * @property slotCount number of slots in the primary group.
 * @property slots the primary group's slots.
 * @property vtableGroups every vtable group of the class.
 */
data class ClassInfo(
    val name: String = "",
    val mangled: String = "",
    val bases: List<String> = emptyList(),
    val vtable: String = "0x0",
    @SerializedName("vtableOffset") val vtableOffset: String = "0x0",
    @SerializedName("typeInfo") val typeInfo: String = "0x0",
    @SerializedName("slotCount") val slotCount: Int = 0,
    val slots: List<VtableSlot> = emptyList(),
    @SerializedName("vtableGroups") val vtableGroups: List<VtableGroup> = emptyList()
)

/**
 * One vtable group of a class with multiple inheritance.
 *
 * @property offsetToTop offset from this subobject to the most-derived object.
 * @property address vtable header address.
 * @property slots the group's slots.
 */
data class VtableGroup(
    @SerializedName("offsetToTop") val offsetToTop: Long = 0,
    val address: String = "0x0",
    val slots: List<VtableSlot> = emptyList()
)

/**
 * One data symbol that was kept out of the function table.
 *
 * @property address virtual address.
 * @property size size recorded by the linker.
 * @property name demangled name.
 * @property mangled mangled name.
 * @property kind `data` or `tls`.
 * @property reason why the symbol is data rather than a function.
 */
data class InternalDataSymbol(
    val address: String = "0x0",
    val size: Long = 0,
    val name: String = "",
    val mangled: String = "",
    val kind: String = "data",
    val reason: String = ""
)

/** Payload returned by the internal-analysis entry point. */
internal data class InternalAnalysisPayload(
    val internal: InternalSummary?,
    @SerializedName("peak_resident_bytes") val peakResidentBytes: Long?
)

/**
 * Result of the internal-analysis entry point.
 *
 * @property summary counts and the NDJSON path.
 * @property peakResidentBytes peak resident set after the pass, when reported.
 */
data class InternalAnalysis(
    val summary: InternalSummary,
    val peakResidentBytes: Long?
)

/** Parses a `0x`-prefixed hex address, returning zero on malformed input. */
fun parseHex(value: String): Long {
    val trimmed = value.trim()
    if (trimmed.isEmpty()) return 0
    return trimmed.removePrefix("0x").removePrefix("0X").toLongOrNull(16) ?: 0
}

/**
 * One hand-maintained internal signature from `patterns.json`.
 *
 * @property name name reported for the resolved address.
 * @property pattern space-separated hex bytes with `??` wildcards.
 * @property resolve `self`, `bl_target`, `adrp_add` or `prologue_back`.
 * @property offset byte adjustment applied to a `self` match.
 */
data class InternalPatternSpec(
    val name: String,
    val pattern: String,
    val resolve: String = "self",
    val offset: Int = 0
)

/**
 * One `.rodata` string anchor from `patterns.json`.
 *
 * @property name name reported for the enclosing function.
 * @property string unique string whose address the function materialises.
 */
data class StringAnchorSpec(
    val name: String,
    val string: String
)

/**
 * Options handed to the internal-analysis entry point.
 *
 * @property includeAllFunctions enumerate every `.eh_frame` function.
 * @property generateSignatures generate and verify a signature per named
 *   function.
 * @property maxSlotsPerClass hard cap on slots read for one class.
 * @property maxSignatures cap on auto-generated signatures; the default
 *   matches the engine so every vtable slot and every symbol-named function
 *   gets one.
 * @property internalPatterns hand-maintained internal signatures.
 * @property stringAnchors `.rodata` string anchors.
 */
data class InternalOptions(
    val includeAllFunctions: Boolean = true,
    val generateSignatures: Boolean = true,
    val maxSlotsPerClass: Int = 4096,
    val maxSignatures: Int = 1_000_000,
    val internalPatterns: List<InternalPatternSpec> = emptyList(),
    val stringAnchors: List<StringAnchorSpec> = emptyList(),
    val categories: com.google.gson.JsonElement? = null,
    val sourceHeader: String = ""
)
