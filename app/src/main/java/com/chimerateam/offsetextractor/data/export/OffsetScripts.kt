package com.chimerateam.offsetextractor.data.export

import com.chimerateam.offsetextractor.ui.state.ScanResultSummary

/**
 * A modder-facing export format.
 *
 * @property label name shown in the Export menu.
 * @property extension file extension of the generated script.
 * @property mimeType MIME type used when the script is shared.
 */
enum class ScriptFormat(val label: String, val extension: String, val mimeType: String) {
    IdaPython("IDA Python", "py", "text/x-python"),
    GhidraScript("Ghidra script", "java", "text/x-java"),
    FridaTypeScript("Frida script", "ts", "text/typescript"),
    CppHeader("C++ header", "hpp", "text/x-c++hdr")
}

/**
 * Renders a scan as the script a reverse-engineering tool loads.
 *
 * Addresses are emitted as RVAs relative to the image base, because that is the
 * value that survives a different load address; each format adds the base back
 * in the way its tool expects.
 */
object OffsetScripts {

    /** Entries one script carries; a larger list would not be usable by hand. */
    const val ENTRY_LIMIT = 20_000

    /**
     * One named address in a script.
     *
     * @property name identifier as the scan reported it.
     * @property rva offset from the image base.
     * @property kind `jni`, `vtable` or `symbol`.
     */
    data class Entry(val name: String, val rva: Long, val kind: String)

    /**
     * Collects the entries a script exports.
     *
     * JNI exports come first, then vtables, then dynamic symbols. A name that
     * appears twice keeps its first, more specific definition.
     *
     * @param summary the completed scan.
     * @return at most [ENTRY_LIMIT] entries, ordered by name.
     */
    fun entries(summary: ScanResultSummary): List<Entry> {
        val base = summary.imageBase
        val seen = HashSet<String>()
        val out = ArrayList<Entry>()
        fun add(name: String, address: Long, kind: String) {
            if (out.size >= ENTRY_LIMIT || name.isBlank() || address == 0L) return
            if (!seen.add(name)) return
            out += Entry(name = name, rva = address - base, kind = kind)
        }
        summary.jni?.offsets.orEmpty().forEach { add(it.javaName, it.address, "jni") }
        summary.vtables.entries.values.forEach { add(it.name, it.vtableAddress, "vtable") }
        summary.symbols.forEach { add(it.name, it.address, "symbol") }
        return out.sortedBy { it.name.lowercase() }
    }

    /**
     * Renders [summary] in [format].
     *
     * @param summary the completed scan.
     * @param format destination script dialect.
     * @return the script, ending in a newline.
     */
    fun render(summary: ScanResultSummary, format: ScriptFormat): String {
        val entries = entries(summary)
        return when (format) {
            ScriptFormat.IdaPython -> idaPython(summary, entries)
            ScriptFormat.GhidraScript -> ghidraScript(summary, entries)
            ScriptFormat.FridaTypeScript -> fridaTypeScript(summary, entries)
            ScriptFormat.CppHeader -> cppHeader(summary, entries)
        }
    }

    /**
     * Makes [name] a valid identifier in every target language.
     *
     * C++ names carry `::`, `~`, `<` and `>`, none of which a label accepts.
     */
    fun identifier(name: String): String {
        val cleaned = buildString(name.length) {
            name.forEach { character ->
                append(if (character.isLetterOrDigit() || character == '_') character else '_')
            }
        }.trim('_')
        val safe = cleaned.ifBlank { "offset" }
        return if (safe.first().isDigit()) "_$safe" else safe
    }

    private fun header(summary: ScanResultSummary, comment: String, count: Int): String =
        buildString {
            appendLine("$comment generated by Bedrock-Offsets")
            appendLine("$comment build ${summary.buildId.ifBlank { "unknown" }}")
            appendLine("$comment architecture ${summary.architecture.ifBlank { "unknown" }}")
            appendLine("$comment $count named offsets, RVAs relative to the image base")
        }

    private fun idaPython(summary: ScanResultSummary, entries: List<Entry>): String = buildString {
        append(header(summary, "#", entries.size))
        appendLine("import idc")
        appendLine()
        appendLine("IMAGE_BASE = 0x%x".format(summary.imageBase))
        appendLine()
        appendLine("def apply_offsets():")
        entries.forEach { entry ->
            appendLine(
                "    idc.set_name(IMAGE_BASE + 0x%x, %s, idc.SN_NOWARN)".format(
                    entry.rva,
                    quote(identifier(entry.name))
                )
            )
        }
        appendLine()
        appendLine()
        appendLine("if __name__ == \"__main__\":")
        appendLine("    apply_offsets()")
    }

    private fun ghidraScript(summary: ScanResultSummary, entries: List<Entry>): String =
        buildString {
            append(header(summary, "//", entries.size))
            appendLine("//@category BedrockOffsets")
            appendLine("import ghidra.app.script.GhidraScript;")
            appendLine("import ghidra.program.model.symbol.SourceType;")
            appendLine()
            appendLine("public class BedrockOffsetsScript extends GhidraScript {")
            appendLine(
                "    private static final long IMAGE_BASE = 0x%xL;".format(summary.imageBase)
            )
            appendLine()
            appendLine("    @Override")
            appendLine("    public void run() throws Exception {")
            appendLine(
                "        long delta = currentProgram.getImageBase().getOffset() - IMAGE_BASE;"
            )
            entries.forEach { entry ->
                appendLine(
                    "        createLabel(toAddr(delta + 0x%xL), %s, true);".format(
                        entry.rva,
                        quote(identifier(entry.name))
                    )
                )
            }
            appendLine("    }")
            appendLine("}")
        }

    private fun fridaTypeScript(summary: ScanResultSummary, entries: List<Entry>): String =
        buildString {
            append(header(summary, "//", entries.size))
            appendLine("const moduleName = \"libminecraftpe.so\";")
            appendLine("const base = Module.getBaseAddress(moduleName);")
            appendLine()
            appendLine("const offsets: Record<string, number> = {")
            entries.forEach { entry ->
                appendLine("  %s: 0x%x,".format(quote(entry.name), entry.rva))
            }
            appendLine("};")
            appendLine()
            appendLine("export function attach(name: keyof typeof offsets): void {")
            appendLine("  Interceptor.attach(base.add(offsets[name]), {")
            appendLine("    onEnter(_args) {")
            appendLine("      // Set a breakpoint here or call send(name) to log the call.")
            appendLine("    }")
            appendLine("  });")
            appendLine("}")
            appendLine()
            appendLine("// Attach to the functions you need, for example:")
            entries.take(3).forEach { entry ->
                appendLine("// attach(%s);".format(quote(entry.name)))
            }
        }

    private fun cppHeader(summary: ScanResultSummary, entries: List<Entry>): String = buildString {
        append(header(summary, "//", entries.size))
        appendLine("#pragma once")
        appendLine()
        appendLine("#include <cstdint>")
        appendLine()
        appendLine("namespace bedrock_offsets {")
        entries.forEach { entry ->
            appendLine(
                "inline constexpr std::uintptr_t %s = 0x%x;".format(
                    identifier(entry.name),
                    entry.rva
                )
            )
        }
        appendLine("}  // namespace bedrock_offsets")
    }

    private fun quote(value: String): String = "\"" + value.replace("\"", "\\\"") + "\""
}
